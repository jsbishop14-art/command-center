#!/usr/bin/env tsx
// Generate TypeScript row types from the live schema (process.md section 6: generated types).
// Runs the migrations into a throwaway in-memory database, introspects it, and writes
// src/lib/db-types.ts. Re-run after changing a migration; CI checks it is in sync.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Database from "better-sqlite3";
import { runMigrations } from "../src/lib/migrations";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "db-types.ts");

function pascal(name: string): string {
  return name
    .split("_")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

function tsType(sqlType: string): string {
  const t = sqlType.toUpperCase();
  if (t.includes("INT")) return "number";
  if (t.includes("REAL") || t.includes("FLOA") || t.includes("DOUB")) return "number";
  if (t.includes("BLOB")) return "Buffer";
  return "string";
}

function generate(): string {
  const db = new Database(":memory:");
  db.pragma("foreign_keys = ON");
  runMigrations(db);

  const tables = (
    db
      .prepare(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
      )
      .all() as { name: string }[]
  ).map((r) => r.name);

  const blocks: string[] = [];
  for (const table of tables) {
    const cols = db.prepare(`PRAGMA table_info(${table})`).all() as {
      name: string;
      type: string;
      notnull: number;
      pk: number;
    }[];
    const fields = cols
      .map((c) => {
        const nullable = c.notnull === 0 && c.pk === 0;
        return `  ${c.name}${nullable ? "?" : ""}: ${tsType(c.type)}${nullable ? " | null" : ""};`;
      })
      .join("\n");
    blocks.push(`export interface ${pascal(table)} {\n${fields}\n}`);
  }
  db.close();

  return (
    "// GENERATED by `npm run gen:types` from the migrations. Do not edit by hand.\n" +
    "// Re-run after changing a migration.\n\n" +
    blocks.join("\n\n") +
    "\n"
  );
}

const out = generate();
fs.writeFileSync(OUT, out);
console.log(`gen:types: wrote ${path.relative(process.cwd(), OUT)}`);
